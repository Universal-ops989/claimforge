"""Migration tests.

These are synchronous on purpose: Alembic's env.py runs its own event loop.
"""

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory

API_ROOT = Path(__file__).resolve().parents[2]


@pytest.fixture
def alembic_config(database_url: str) -> Config:
    config = Config(str(API_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(API_ROOT / "migrations"))
    config.set_main_option("sqlalchemy.url", database_url)
    config.attributes["configure_logger"] = False
    return config


def test_single_head() -> None:
    script = ScriptDirectory(str(API_ROOT / "migrations"))

    assert len(script.get_heads()) <= 1, "Merge migration branches before merging the PR"


def test_upgrade_downgrade_round_trip(alembic_config: Config) -> None:
    # Every migration must be reversible: up, all the way down, and up again.
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, "base")
    command.upgrade(alembic_config, "head")


def test_models_and_migrations_do_not_drift(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")

    # Raises AutogenerateDiffsDetected if a model changed without a migration.
    command.check(alembic_config)
